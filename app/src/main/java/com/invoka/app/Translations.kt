import androidx.compose.runtime.Composable
import androidx.compose.runtime.compositionLocalOf

val LocalLang = compositionLocalOf { "ar" }

/** Arabic source string -> English. Use inside composables. */
@Composable
fun tr(ar: String): String = trL(LocalLang.current, ar)

/** Same as [tr] but usable outside composition (callbacks, PDF, domain code). */
